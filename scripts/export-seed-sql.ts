/**
 * Offline seed exporter.
 *
 * Writes `supabase/seed/seed.sql` from the captured Rebix catalog so a fresh
 * Supabase project can be seeded from the SQL editor when the machine running
 * the app cannot reach the database directly (or when CI must stay offline).
 *
 * The output is idempotent: providers/categories upsert by slug, endpoints
 * insert with `on conflict (source_key) do nothing` and model aliases with
 * `on conflict (slug) do nothing`. Sensitive values are never written.
 *
 * Usage: npm run seed:sql [-- --stdout]
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const endpoints = JSON.parse(
  readFileSync(join(process.cwd(), "tests/fixtures/rebix-normalized.json"), "utf8"),
) as Array<{
  name: string;
  slug: string;
  path: string;
  method: string;
  description: string | null;
  category_slug: string;
  query_params: unknown[];
  is_nsfw: boolean;
  source_key: string;
  source_url: string;
  request_example: unknown;
  example_params: Record<string, string>;
  verification_status: "unverified" | "verified" | "failed";
  last_error: string | null;
  response_example: unknown;
}>;

const CATEGORY_NAMES: Record<string, string> = {
  ai: "AI",
  downloader: "Downloaders",
  search: "Search",
  anime: "Anime",
  tools: "Tools",
  "tools-extra": "Extra Tools",
  random: "Random",
  images: "Images",
  nsfw: "NSFW",
  system: "System",
};

const MANIFEST_TIMESTAMP = "2026-10-17T16:39:11.102Z";
const MANIFEST_URL = "https://api-rebix.zone.id/allEnds";
const BASE_URL = "https://api-rebix.zone.id";

function text(value: string | null): string {
  if (value === null) return "null";
  return `'${value.replace(/'/g, "''")}'`;
}

function json(value: unknown): string {
  if (value === null || value === undefined) return "null";
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

function categorySlugOf(endpoint: { category_slug: string }): string {
  return endpoint.category_slug;
}

const categorySlugs = [...new Set(endpoints.map(categorySlugOf))];
const lines: string[] = [];

lines.push("-- Generated by scripts/export-seed-sql.ts — do not edit by hand.");
lines.push("-- Idempotent seed for the public Rebix catalog captured at " + MANIFEST_TIMESTAMP);
lines.push("-- Safe to run multiple times: existing rows and verification results are preserved.");
lines.push("");
lines.push("begin;");
lines.push("");
lines.push("insert into public.providers (slug, name, description, homepage_url, base_url, docs_url, allowed_hosts, discovery_adapter, discovery_config)");
lines.push("values (");
lines.push("  'rebix', 'Rebix API',");
lines.push("  'Public multi-purpose API provider discovered at api-rebix.zone.id. Catalog imported from the public /allEnds manifest.',");
lines.push("  'https://api-rebix.zone.id/', 'https://api-rebix.zone.id', 'https://api-rebix.zone.id/',");
lines.push("  array['api-rebix.zone.id']::text[], 'rebix_manifest', '{\"manifest_path\":\"/allEnds\"}'::jsonb");
lines.push(")");
lines.push("on conflict (slug) do update set");
lines.push("  name = excluded.name, description = excluded.description,");
lines.push("  homepage_url = excluded.homepage_url, base_url = excluded.base_url,");
lines.push("  docs_url = excluded.docs_url, allowed_hosts = excluded.allowed_hosts,");
lines.push("  discovery_adapter = excluded.discovery_adapter, discovery_config = excluded.discovery_config;");
lines.push("");
lines.push("insert into public.categories (slug, name, description, sort_order) values");
lines.push(
  categorySlugs
    .map((slug, index) => {
      const name = CATEGORY_NAMES[slug] ?? slug;
      return `  (${text(slug)}, ${text(name)}, ${text(`Rebix ${name} endpoints.`)}, ${index})`;
    })
    .join(",\n") + "\non conflict (slug) do nothing;",
);
lines.push("");

for (const endpoint of endpoints) {
  const requestExample = endpoint.request_example;
  lines.push(
    `-- ${endpoint.name} (${endpoint.method} ${endpoint.path})`,
  );
  lines.push("insert into public.apis (");
  lines.push(
    "  owner_id, provider_id, category_id, slug, name, description, base_url, path, method,",
  );
  lines.push(
    "  query_params, path_params, headers_schema, body_schema, auth_type, auth_config_meta,",
  );
  lines.push(
    "  content_type, request_example, response_example, docs_url, source_url, discovery_source,",
  );
  lines.push(
    "  discovery_metadata, verification_status, last_status_code, last_tested_at, last_error,",
  );
  lines.push(
    "  is_public, is_enabled, is_nsfw, is_managed, allow_extra_query, supports_streaming, timeout_ms, source_key",
  );
  lines.push(") values (");
  lines.push("  null,");
  lines.push("  (select id from public.providers where slug = 'rebix'),");
  lines.push(`  (select id from public.categories where slug = ${text(endpoint.category_slug)}),`);
  lines.push(
    `  ${text(endpoint.slug)}, ${text(endpoint.name)}, ${text(endpoint.description)}, ${text(BASE_URL)}, ${text(endpoint.path)}, ${text(endpoint.method)},`,
  );
  lines.push(
    `  ${json(endpoint.query_params)}, '[]'::jsonb, '[]'::jsonb, null, 'none', '{}'::jsonb,`,
  );
  lines.push(
    `  'application/json', ${json(requestExample)}, ${json(endpoint.response_example)}, 'https://api-rebix.zone.id/', ${text(endpoint.source_url)}, 'rebix_manifest',`,
  );
  lines.push(
    `  ${json({
      discovery: "rebix_manifest",
      manifest_url: MANIFEST_URL,
      manifest_category: endpoint.category_slug,
      category_key: endpoint.category_slug,
      example_params: endpoint.example_params,
      manifest_timestamp: MANIFEST_TIMESTAMP,
      discovered_at: MANIFEST_TIMESTAMP,
    })},`,
  );
  lines.push(
    `  ${text(endpoint.verification_status)}, ${endpoint.verification_status === "unverified" ? "null" : "200"}, ${
      endpoint.verification_status === "unverified" ? "null" : "now()"
    }, ${text(endpoint.last_error)},`,
  );
  lines.push(
    `  true, true, ${endpoint.is_nsfw}, true, false, false, 15000, ${text(endpoint.source_key)}`,
  );
  lines.push(") on conflict (source_key) do nothing;");
  lines.push("");
}

const models = [
  {
    slug: "rebix-claude-haiku",
    name: "Claude Haiku 4.5 via Rebix",
    apiSlug: "claude-haiku",
    path: "/api/claude-haiku",
    responsePaths: ["response", "message", "result", "reply", "answer"],
    enabled: true,
    description:
      "Maps OpenAI chat messages onto the documented Rebix GET /api/claude-haiku?q= endpoint. Rebix is not an OpenAI-compatible upstream: streaming, tool calling and token usage reporting are unavailable.",
  },
  {
    slug: "rebix-gemini",
    name: "Gemini via Rebix",
    apiSlug: "gemini",
    path: "/api/gemini",
    responsePaths: ["message", "response", "result", "reply", "answer"],
    enabled: true,
    description:
      "Maps OpenAI chat messages onto the documented Rebix GET /api/gemini?q= endpoint. Not an OpenAI-compatible upstream; no streaming, tools or usage reporting.",
  },
  {
    slug: "rebix-deepseek-v3",
    name: "DeepSeek V3 via Rebix (disabled)",
    apiSlug: "deepseek-v3",
    path: "/api/deepseek-v3",
    responsePaths: ["message", "response", "result", "reply", "answer"],
    enabled: false,
    description:
      'Disabled on purpose: at discovery time the provider returned HTTP 422 ("The selected messages.0.role is invalid") for this route. It is registered so the failure is documented, not hidden, and can be enabled after the provider fixes it.',
  },
];

for (const model of models) {
  lines.push(`-- AI alias ${model.slug}`);
  lines.push("insert into public.ai_models (");
  lines.push(
    "  owner_id, provider_id, api_id, slug, name, description, adapter, chat_path, auth_type, auth_config_meta, config, capabilities, is_public, is_enabled",
  );
  lines.push(") values (");
  lines.push("  null, (select id from public.providers where slug = 'rebix'),");
  lines.push(
    `  (select id from public.apis where path = ${text(model.path)} and method = 'GET' limit 1),`,
  );
  lines.push(
    `  ${text(model.slug)}, ${text(model.name)}, ${text(model.description)}, 'rebix_text', '/chat/completions', 'none', '{}'::jsonb,`,
  );
  lines.push(
    `  ${json({ query_param: "q", response_paths: model.responsePaths })},`,
  );
  lines.push(
    `  ${json({ chat: true, streaming: false, tools: false, usage: false })}, true, ${model.enabled}`,
  );
  lines.push(") on conflict (slug) do nothing;");
  lines.push("");
}

lines.push("insert into public.discovery_runs (");
lines.push(
  "  user_id, provider_id, adapter, source_url, status, attempted_methods, notes, created_count, updated_count, unchanged_count, failed_count, endpoint_ids, started_at, finished_at",
);
lines.push(")");
lines.push("select");
lines.push("  null, p.id, 'rebix_manifest', 'https://api-rebix.zone.id/', 'success',");
lines.push(
  `  ${json([
    { method: "homepage", target: "https://api-rebix.zone.id/", outcome: "success", status: 200 },
    {
      method: "javascript_bundle_scan",
      target: "https://api-rebix.zone.id/script.js",
      outcome: "success",
      status: 200,
      detail: "Bundle fetches /allEnds and renders tables from it.",
    },
    { method: "manifest_probe", target: MANIFEST_URL, outcome: "success", status: 200, endpoints: endpoints.length },
    { method: "openapi_probe", target: "https://api-rebix.zone.id/openapi.json", outcome: "not_found", status: 404 },
    { method: "openapi_probe", target: "https://api-rebix.zone.id/swagger.json", outcome: "not_found", status: 404 },
  ])},`,
);
lines.push(
  "  'Seeded from a captured live discovery run. Verification reflects real requests: 7 verified, 2 failed with upstream 422, 46 unverified.',",
);
lines.push(
  `  ${endpoints.length}, 0, 0, 0, array(select id from public.apis), ${text(MANIFEST_TIMESTAMP)}, now()`,
);
lines.push("from public.providers p where p.slug = 'rebix'");
lines.push("and not exists (select 1 from public.discovery_runs where source_url = 'https://api-rebix.zone.id/');");
lines.push("");
lines.push("commit;");
lines.push("");

const sql = lines.join("\n");
if (process.argv.includes("--stdout")) {
  process.stdout.write(sql);
} else {
  const target = join(process.cwd(), "supabase/seed/seed.sql");
  mkdirSync(join(process.cwd(), "supabase/seed"), { recursive: true });
  writeFileSync(target, sql);
  console.log(`Wrote ${target} (${sql.split("\n").length} lines, ${endpoints.length} endpoints).`);
  console.log("Paste it into the Supabase SQL editor, or run it with psql.");
}
